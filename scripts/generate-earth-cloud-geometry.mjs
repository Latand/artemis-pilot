import { buildCappedEarthCloudUnitMesh } from './build-earth-cloud-mesh.mjs';
import { reorderCloudTriangles } from './reorder-cloud-triangles.mjs';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const { positions, uv, indices: originalIndices } = buildCappedEarthCloudUnitMesh();
// Offline only: reorder oriented triangles; never remap a vertex or UV.
const indices = reorderCloudTriangles(originalIndices, positions.length / 3);
if (!(indices instanceof Uint16Array)) throw new Error('Cloud geometry must retain bounded Uint16 indices');
const bytes = Buffer.alloc(positions.byteLength + uv.byteLength + indices.byteLength);
let offset = 0;
for (const array of [positions, uv]) for (const value of array) { bytes.writeFloatLE(value, offset); offset += 4; }
for (const value of indices) { bytes.writeUInt16LE(value, offset); offset += 2; }
const sha = createHash('sha256').update(bytes).digest('hex');
const result = `// Generated by scripts/generate-earth-cloud-geometry.mjs; do not hand-edit.\n// Unit-radius indexed detail18 geodesic belt with5-degree equirectangular caps; fixed SphereGeometry UV phase.\n// Little-endian Float32 positions + UVs, then Uint16 indices; normals use radial positions.\nexport const CLOUD_VERTEX_COUNT = ${positions.length / 3};\nexport const CLOUD_TRIANGLE_COUNT = ${indices.length / 3};\nexport const CLOUD_DATA_SHA256 = '${sha}';\nexport const CLOUD_UNIT_DATA = '${bytes.toString('base64')}';\n`;
const path = new URL('../src/render/earthCloudGeometryData.js', import.meta.url);
if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== result) throw new Error('Generated cloud geometry differs; inspect and regenerate deliberately');
    console.log(`Cloud geometry source matches generator: ${sha}`);
} else {
    await writeFile(path, result);
    console.log(JSON.stringify({ vertices: positions.length / 3, triangles: indices.length / 3, bytes: bytes.length, sha256: sha }));
}
